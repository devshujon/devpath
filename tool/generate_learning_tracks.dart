// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

import 'learning_tracks/track_specs.dart';

void main() {
  final repo = Directory.current;
  if (!File('pubspec.yaml').existsSync()) {
    stderr.writeln('Run from repository root: dart run tool/generate_learning_tracks.dart');
    exit(1);
  }

  for (final spec in allGeneratedTracks) {
    _writeTrackDart(repo, spec);
    _writeCurriculumAssets(repo, spec);
  }
  print('Generated ${allGeneratedTracks.length} tracks.');
}

void _writeTrackDart(Directory repo, TrackSpec spec) {
  final listName = _dartFileName(spec.trackKey);
  final fileStem = _dartFilePath(spec.trackKey);
  final lessons = _lessonsFor(spec);
  final buffer = StringBuffer()
    ..writeln("import '../models/lesson.dart';")
    ..writeln()
    ..writeln('/// Generated by tool/generate_learning_tracks.dart — do not edit by hand.')
    ..writeln('const List<Lesson> $listName = [');
  for (final l in lessons) {
    buffer.writeln('  ${l.toDartConst()},');
  }
  buffer.writeln('];');
  final out = File('lib/features/learning/data/$fileStem.dart');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(buffer.toString());
  print('Wrote ${out.path} (${lessons.length} lessons)');
}

void _writeCurriculumAssets(Directory repo, TrackSpec spec) {
  final dir = Directory('assets/curriculum/${spec.trackKey}');
  dir.createSync(recursive: true);
  for (final l in _lessonsFor(spec)) {
    final json = _curriculumJson(l, spec);
    final path = '${dir.path}/${l.id}.json';
    File(path).writeAsStringSync(const JsonEncoder.withIndent('  ').convert(json));
  }
  print('Wrote curriculum JSON under ${dir.path}');
}

List<_GenLesson> _lessonsFor(TrackSpec spec) {
  final out = <_GenLesson>[];
  var n = 1;
  for (final diff in ['beginner', 'intermediate', 'advanced']) {
    final titles = switch (diff) {
      'beginner' => spec.beginner,
      'intermediate' => spec.intermediate,
      _ => spec.advanced,
    };
    for (final title in titles) {
      final id = '${spec.trackKey}_${n.toString().padLeft(2, '0')}';
      out.add(
        _GenLesson(
          id: id,
          title: title,
          difficulty: diff,
          trackKey: spec.trackKey,
          module: spec.moduleLabel,
          index: n,
        ),
      );
      n++;
    }
  }
  return out;
}

Map<String, dynamic> _curriculumJson(_GenLesson l, TrackSpec spec) {
  final lang = _contentLang(spec.trackKey);
  final code = _sampleCode(l, lang);
  final security = _securityNote(l, spec.trackKey);
  return {
    'schemaVersion': 2,
    'id': l.id,
    'track': spec.trackKey,
    'difficulty': l.difficulty,
    'title': l.title,
    'summary': l.summary,
    'estimatedMinutes': 12,
    'objectives': [
      'Explain ${l.title} in practical web-development terms',
      'Recognize how ${spec.moduleLabel} connects to HTML, CSS, and JavaScript',
      'Apply safe habits and avoid common mistakes',
    ],
    'content': [
      {
        'type': 'summary',
        'md':
            '**${l.title}** — ${l.summary}',
      },
      {
        'type': 'heading',
        'text': 'Core idea',
        'level': 2,
      },
      {
        'type': 'prose',
        'md': l.coreProse(spec.moduleLabel),
      },
      if (code.isNotEmpty)
        {
          'type': 'code',
          'lang': lang,
          'runnable': lang == 'html' || lang == 'javascript',
          'caption': lang == 'php' || lang == 'sql' || lang == 'python'
              ? 'Study this example offline. DevPath does not execute $lang on device.'
              : 'Try this in the playground when runnable.',
          'code': code,
        },
      if (security != null)
        {
          'type': 'callout',
          'variant': 'warning',
          'md': security,
        },
      {
        'type': 'heading',
        'text': 'Best practices',
        'level': 2,
      },
      {
        'type': 'prose',
        'md':
            '- Prefer clarity and small steps over clever shortcuts.\n- Validate on the **server** for anything security-sensitive (even when you also validate in the browser).\n- Keep secrets out of source control and client-side code.',
      },
      {
        'type': 'heading',
        'text': 'Common mistakes',
        'level': 2,
      },
      {
        'type': 'prose',
        'md': l.mistakes,
      },
    ],
    'quickRecap': [
      l.title,
      'Practice with the quiz — execution on device is limited to HTML/CSS/JS in the playground.',
    ],
    'exercise': {
      'prompt':
          'Review the example, then open the playground only when the lesson uses HTML/CSS/JS starter code. Complete the quiz to earn XP.',
      'starterCode': const {'html': '', 'css': '', 'js': ''},
      'checks': [],
    },
  };
}

class _GenLesson {
  final String id;
  final String title;
  final String difficulty;
  final String trackKey;
  final String module;
  final int index;

  _GenLesson({
    required this.id,
    required this.title,
    required this.difficulty,
    required this.trackKey,
    required this.module,
    required this.index,
  });

  String get summary =>
      'Offline lesson ${index} in the $module track ($difficulty).';

  String coreProse(String moduleLabel) {
    return 'This lesson covers **$title** as part of $moduleLabel. '
        'DevPath bundles the reading and quiz offline; run server-side PHP, SQL engines, '
        'or Python only on your computer when a lesson says to practice locally.';
  }

  String get mistakes =>
      'Skipping validation, copying outdated examples, or assuming every SQL dialect behaves exactly like MySQL.';

  String toDartConst() {
    final diff = switch (difficulty) {
      'beginner' => 'Difficulty.beginner',
      'intermediate' => 'Difficulty.intermediate',
      _ => 'Difficulty.advanced',
    };
    final track = _dartTrackEnum(trackKey);
    final desc = summary.replaceAll("'", "\\'");
    final qs = _quizQuestions();
    return '''Lesson(
    id: '$id',
    title: '${title.replaceAll("'", "\\'")}',
    description: '$desc',
    module: '$module',
    difficulty: $diff,
    track: $track,
    estimatedMinutes: 12,
    xpReward: 50,
    starterCode: const {'html': '', 'css': '', 'js': ''},
    quizQuestions: [
$qs
    ],
  )''';
  }

  String _quizQuestions() {
    final q1 = _q(
      'What is the main focus of “$title”?',
      [
        'A unrelated desktop-only topic',
        title,
        'Replacing all HTML with PHP',
        'Disabling HTTPS everywhere',
      ],
      1,
      '$title is the subject of this lesson.',
    );
    final q2 = _q(
      'Where should you validate untrusted user input for a production web app?',
      [
        'Only in CSS',
        'Only in the browser',
        'On the server (and optionally in the browser for UX)',
        'In a comment block',
      ],
      2,
      'Client-side checks help UX; server-side validation is required for security.',
    );
    final q3 = _q(
      'Can DevPath execute ${module} code on your phone for this lesson?',
      [
        'Yes, full production runtime is built in',
        'No — study examples offline; use a computer for ${module} runtimes unless the playground supports HTML/CSS/JS',
        'Only on iOS',
        'Only with internet',
      ],
      1,
      'Offline-first: quizzes and reading work offline; runtimes are limited on device.',
    );
    return [q1, q2, q3].join(',\n');
  }

  String _q(
    String question,
    List<String> options,
    int correct,
    String explanation,
  ) {
    final opts = options.map((o) => "'${o.replaceAll("'", "\\'")}'").join(', ');
    return '''      QuizQuestion(
        question: '${question.replaceAll("'", "\\'")}',
        options: [$opts],
        correctIndex: $correct,
        explanation: '${explanation.replaceAll("'", "\\'")}',
      )''';
  }
}

String _dartTrackEnum(String trackKey) => switch (trackKey) {
      'php' => 'LessonTrack.php',
      'sql' => 'LessonTrack.sql',
      'typescript' => 'LessonTrack.typescript',
      'python' => 'LessonTrack.python',
      'web_essentials' => 'LessonTrack.webEssentials',
      _ => throw ArgumentError(trackKey),
    };

String _dartFileName(String trackKey) => switch (trackKey) {
      'php' => 'phpLessons',
      'sql' => 'sqlLessons',
      'typescript' => 'typescriptLessons',
      'python' => 'pythonLessons',
      'web_essentials' => 'webEssentialsLessons',
      _ => throw ArgumentError(trackKey),
    };

String _dartFilePath(String trackKey) => switch (trackKey) {
      'php' => 'php_lessons',
      'sql' => 'sql_lessons',
      'typescript' => 'typescript_lessons',
      'python' => 'python_lessons',
      'web_essentials' => 'web_essentials_lessons',
      _ => throw ArgumentError(trackKey),
    };

String _contentLang(String trackKey) => switch (trackKey) {
      'php' => 'php',
      'sql' => 'sql',
      'typescript' => 'typescript',
      'python' => 'python',
      _ => 'markdown',
    };

String _sampleCode(_GenLesson l, String lang) {
  return switch (lang) {
    'php' => "<?php\n// ${l.title}\n\$name = htmlspecialchars(\$_POST['name'] ?? '', ENT_QUOTES, 'UTF-8');\necho \"Hello, \$name\";\n",
    'sql' =>
        '-- ${l.title}\n-- MySQL example\nSELECT id, title FROM posts WHERE status = \'published\' ORDER BY created_at DESC LIMIT 10;\n',
    'typescript' =>
        '// ${l.title}\ntype ApiUser = { id: number; name: string };\nconst parseUser = (data: unknown): ApiUser | null => {\n  if (typeof data !== "object" || data === null) return null;\n  const o = data as Record<string, unknown>;\n  if (typeof o.id !== "number" || typeof o.name !== "string") return null;\n  return { id: o.id, name: o.name };\n};\n',
    'python' =>
        '# ${l.title}\n# Run on your computer — not in the DevPath app runtime.\ndef greet(name: str) -> str:\n    return f"Hello, {name}"\n\nif __name__ == "__main__":\n    print(greet("DevPath"))\n',
    _ => '',
  };
}

String? _securityNote(_GenLesson l, String trackKey) {
  final t = l.title.toLowerCase();
  if (t.contains('password') || t.contains('authentication') || t.contains('secret')) {
    return 'Never store plaintext passwords. Use modern hashing (e.g. `password_hash` in PHP) and protect secrets with environment configuration.';
  }
  if (t.contains('sql injection') || t.contains('prepared')) {
    return 'Always use parameterized queries / prepared statements. Never concatenate raw user input into SQL strings.';
  }
  if (t.contains('upload') || t.contains('file')) {
    return 'Validate file type and size on the server, store uploads outside the web root, and never trust client-provided paths.';
  }
  if (t.contains('xss') || t.contains('escaping')) {
    return 'Treat all dynamic output as untrusted until escaped for the correct context (HTML, URL, JS).';
  }
  if (trackKey == 'sql' && t.contains('delete')) {
    return 'Always use WHERE with DELETE in production scripts, and prefer transactions for multi-step changes.';
  }
  return null;
}
